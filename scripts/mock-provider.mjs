/**
 * Local OpenAI-compatible mock provider for developing without real API keys.
 *
 *   npm run mock:provider
 *
 * Then add a key in Settings → Providers:
 *   provider: OpenAI-compatible
 *   base URL: http://localhost:8787/v1
 *   API key:  anything (e.g. "mock")
 *   model:    mock-1
 *
 * Behavior:
 * - GET /v1/models lists "mock-1".
 * - Chat requests stream a Markdown reply echoing the last user message.
 * - If tools are offered and the user asks for a pdf / deck / document / page,
 *   the mock emits a tool call so the agent loop can be exercised end to end.
 */
import http from 'node:http';

const PORT = Number(process.env.MOCK_PROVIDER_PORT ?? 8787);

const TOOL_MATCHERS = [
  { tool: 'createPdf', pattern: /pdf|report|отчет|отчёт/i },
  { tool: 'createPresentation', pattern: /deck|presentation|slides|презентац/i },
  { tool: 'createDocument', pattern: /docx|word document/i },
  { tool: 'createHtmlArtifact', pattern: /html|page|dashboard|landing/i },
];

function toolArguments(tool) {
  switch (tool) {
    case 'createPdf':
      return JSON.stringify({
        title: 'Mock report',
        subtitle: 'Generated by the local mock provider',
        sections: [
          {
            heading: 'Summary',
            paragraphs: ['This PDF was produced by the MindLarp Chat agent loop.'],
            bullets: ['Streaming works', 'Tools work', 'Unicode works: привет'],
          },
        ],
      });
    case 'createPresentation':
      return JSON.stringify({
        title: 'Mock deck',
        slides: [
          { title: 'Hello', bullets: ['From the mock provider'] },
          { title: 'Thanks', section: true },
        ],
      });
    case 'createDocument':
      return JSON.stringify({
        title: 'Mock document',
        sections: [{ heading: 'Body', paragraphs: ['A DOCX from the mock provider.'] }],
      });
    default:
      return JSON.stringify({
        title: 'Mock page',
        html: '<!doctype html><html><body style="font-family:sans-serif;padding:2rem"><h1>Mock artifact</h1><p>Hello from the agent loop.</p></body></html>',
      });
  }
}

function sse(res, payload) {
  res.write(`data: ${JSON.stringify(payload)}\n\n`);
}

function chunkBase(model) {
  return {
    id: `chatcmpl-mock-${Date.now()}`,
    object: 'chat.completion.chunk',
    created: Math.floor(Date.now() / 1000),
    model,
  };
}

function streamText(res, model, text, usage) {
  const base = chunkBase(model);
  const words = text.split(/(?<= )/);
  for (const word of words) {
    sse(res, { ...base, choices: [{ index: 0, delta: { content: word }, finish_reason: null }] });
  }
  sse(res, { ...base, choices: [{ index: 0, delta: {}, finish_reason: 'stop' }] });
  if (usage) {
    sse(res, { ...base, choices: [], usage });
  }
  res.write('data: [DONE]\n\n');
  res.end();
}

function streamToolCall(res, model, tool) {
  const base = chunkBase(model);
  const args = toolArguments(tool);
  sse(res, {
    ...base,
    choices: [
      {
        index: 0,
        delta: {
          role: 'assistant',
          tool_calls: [
            {
              index: 0,
              id: 'call_mock_1',
              type: 'function',
              function: { name: tool, arguments: '' },
            },
          ],
        },
        finish_reason: null,
      },
    ],
  });
  for (let i = 0; i < args.length; i += 24) {
    sse(res, {
      ...base,
      choices: [
        {
          index: 0,
          delta: { tool_calls: [{ index: 0, function: { arguments: args.slice(i, i + 24) } }] },
          finish_reason: null,
        },
      ],
    });
  }
  sse(res, { ...base, choices: [{ index: 0, delta: {}, finish_reason: 'tool_calls' }] });
  res.write('data: [DONE]\n\n');
  res.end();
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://localhost:${PORT}`);

  if (req.method === 'GET' && url.pathname === '/v1/models') {
    res.writeHead(200, { 'content-type': 'application/json' });
    res.end(JSON.stringify({ data: [{ id: 'mock-1', object: 'model' }] }));
    return;
  }

  if (req.method === 'POST' && url.pathname === '/v1/chat/completions') {
    let body = '';
    for await (const part of req) body += part;
    const parsed = JSON.parse(body || '{}');
    const messages = parsed.messages ?? [];
    const model = parsed.model ?? 'mock-1';
    const lastUser = [...messages].reverse().find((message) => message.role === 'user');
    const userText =
      typeof lastUser?.content === 'string'
        ? lastUser.content
        : (lastUser?.content ?? [])
            .filter((part) => part.type === 'text')
            .map((part) => part.text)
            .join(' ');

    const hasToolResult = messages.some((message) => message.role === 'tool');
    const offeredTools = (parsed.tools ?? []).map((tool) => tool.function?.name);
    const matcher = TOOL_MATCHERS.find(
      (entry) => offeredTools.includes(entry.tool) && entry.pattern.test(userText),
    );

    res.writeHead(200, {
      'content-type': 'text/event-stream',
      'cache-control': 'no-cache',
      connection: 'keep-alive',
    });

    const usage = {
      prompt_tokens: 42,
      completion_tokens: 24,
      total_tokens: 66,
    };

    if (matcher && !hasToolResult && parsed.stream !== false) {
      streamToolCall(res, model, matcher.tool);
      return;
    }

    const reply = hasToolResult
      ? 'Done — the artifact is ready above. Let me know if you want changes.'
      : `**Mock reply** from \`${model}\`.\n\nYou said:\n\n> ${userText.slice(0, 400) || '(empty)'}\n\n- Streaming works\n- Markdown works\n\n\`\`\`js\nconsole.log('hello from mock');\n\`\`\``;

    if (parsed.stream === false) {
      res.writeHead(200, { 'content-type': 'application/json' });
      res.end(
        JSON.stringify({
          ...chunkBase(model),
          object: 'chat.completion',
          choices: [
            { index: 0, message: { role: 'assistant', content: reply }, finish_reason: 'stop' },
          ],
          usage,
        }),
      );
      return;
    }

    streamText(res, model, reply, usage);
    return;
  }

  res.writeHead(404, { 'content-type': 'application/json' });
  res.end(JSON.stringify({ error: 'not found' }));
});

server.listen(PORT, () => {
  console.log(`Mock OpenAI-compatible provider listening on http://localhost:${PORT}/v1`);
});
